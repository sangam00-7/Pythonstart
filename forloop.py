#for loops= execute a block of code a fixed number of times 
#you can iterate over a range, string, sequence etc

#to count from 1 to 10
for x in range(1,11):
    print(x)

#to count in reverse order
for x in reversed (range(1,10)):
    print(x)

#iterate over string

name = "Sangam"
for x in name:
    print(x)
